# Inhalt (Daedalus-Teil; Eroberung der Punkte, Ansagen, Tasten und Uebersicht macht die DLL, Kern\CoopFun.cpp):
#  - Siegpunkte je Gilde (FUN_SIEG_*): Punkte halten (+1 je Punkt und Takt), Spieler toeten (+5, Kopfgeld +10), Begleiter
#    (+2), Anfuehrer (+50), Reliquie heimbringen (+100), Weltereignis (+40), Kapitel-Boss (+25). Runde: 1000 Punkte oder
#    60 Minuten - Sieger bekommt Lernpunkte und Gold, dann neue Runde.
#  - Beute je Gilde (FUN_BEUTE_*): Gold fuer alle Spieler der Gilde (jeder PC zahlt seinem Helden die Differenz aus).
#  - Lagerfuehrer: starker NPC im Lager, traegt die Reliquie der Gilde. Faellt er: kein Handel, Wiederbeleben 60 s statt 30 s,
#    nach 5 Minuten kommt er wieder.
#  - Reliquie (ItMi_Fun_Banner_*): vom Anfuehrer erbeuten, ins eigene Lager tragen. Stirbt der Traeger, kehrt sie heim.
#  - Soeldner anheuern beim Haendler (3 Kaempfer, 600 Gold), folgen wie die Begleiter.
#  - Weltereignis alle 15 Minuten (erstes nach 10): Ork-Kriegstrupp, Schwarzer Troll, Untoter Fuerst, Schatzkarawane.
#  - Gilden-Staerken (Miliz Schutz, Soeldner Staerke, Novizen Mana/Magieschutz, Banditen Geschick) - in gen_fun.py.
#  - Schlachtruf (Taste, DLL) und Begleiter-Befehle (Taste, DLL): FUN_SCHLACHTRUF, FUN_BEFEHL, FUN_BEFEHL_HALT.
#  - Zaehlen beim Tod: ZS_Dead (MergeMode) - Spieler auf dem eigenen PC, NPCs nur beim Host (COOP_FUNHOST()).
# Variablen FUN_SIEG_*, FUN_BEUTE_*, FUN_BANNER_NEU_*, FUN_HEUER_* gleicht der Coop als Aenderung ab (Mods\CoopMods.cpp), damit
# gleichzeitige Erhoehungen auf zwei PCs sich addieren.

